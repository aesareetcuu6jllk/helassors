import __main__ as main_module
from telethon import events

# ربط محرك سورس هيلاس
hellas = main_module.hellas

@hellas.on(events.NewMessage(pattern=r"^\.اوامر السحب والنقل$", outgoing=True))
async def fetch_transfer_help(event):
    help_text = """**📦 أوامر السحب والنقل - سورس هيلاس:**

• `.سحب [رابط الكروب]` 
**الشرح:** لسحب يوزرات أعضاء أي مجموعة (عامة أو خاصة أنت فيها) وحفظهم في ملف نصي يرسله السورس لك.

• `.ايقاف السحب` 
**الشرح:** لإيقاف عملية السحب الجارية فوراً وإرسال ما تم جمعه من يوزرات حتى تلك اللحظة.

• `.نقل [رابط كروبك]` 
**الشرح:** (بالرد على ملف اليوزرات) يقوم السورس بإضافة الأشخاص الموجودين في الملف إلى مجموعتك تلقائياً.

⚠️ **ملاحظة:** يفضل استخدام حسابات قديمة للنقل لتجنب الحظر السريع من التليجرام.

✨ **شغل كامل ومضبوط لعيونك!**"""
    await event.edit(help_text)

